import { generateJson } from "@/lib/ai/gemini";
import { assessmentAgentOutputSchema, type AssessmentAgentOutput } from "@/lib/ai/schemas";
import { assessmentPrompt } from "@/lib/ai/prompts";
import { isGeminiConfigured } from "@/lib/ai/model-config";
import type { Agent } from "@/lib/agents/types";

function curatedQuestions(skillId: string, skillName: string): AssessmentAgentOutput {
  return { questions: [{ skillId, questionText: `Which statement best describes the primary purpose of ${skillName}?`, difficulty: "beginner", options: [`Building foundational understanding of ${skillName}`, "Replacing all software testing", "Guaranteeing a job offer", "Eliminating the need for practice"], correctAnswer: `Building foundational understanding of ${skillName}`, explanation: `${skillName} mastery requires understanding its core concepts and applying them with evidence.`, concept: `${skillName} fundamentals` }] };
}

export const assessmentAgent: Agent<"assessment"> = {
  name: "assessment",
  async run(context) {
    const skill = context.skills.find((item) => item.id === context.selectedSkillId) ?? context.skills.find((item) => context.learnerSkills.some((learnerSkill) => learnerSkill.skillId === item.id)) ?? context.skills[0];
    if (!skill) throw new Error("No skill is available for assessment generation.");
    if (!isGeminiConfigured()) return { agent: "assessment", output: curatedQuestions(skill.id, skill.name), explanation: "A clearly labeled curated fallback question was used because Gemini is not configured." };
    const output = await generateJson({ prompt: assessmentPrompt(skill.name, "beginner", 5), schema: assessmentAgentOutputSchema.toJSONSchema(), parse: (value) => assessmentAgentOutputSchema.parse(value), metadata: { feature: "assessment_generation", agent: "assessment" } });
    return { agent: "assessment", output, explanation: "Assessment questions were generated by Gemini, validated with Zod, and are intended to be graded server-side." };
  },
};
